import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {artwork} from './hub-background-source/artwork.mjs';
import {cyberOverlay,overlayAdapters} from './hub-background-source/overlay.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function generateHubBackgrounds(webRoot = root, flutterRoot = null, tokenFile = path.join(webRoot, 'src/design-system/styles/tokens.css')) {
  const source = path.join(webRoot, 'scripts/hub-background-source');
  const raw = fs.readFileSync(path.join(source,'manifest.json'),'utf8');
  const spec = JSON.parse(raw);
  const css = fs.readFileSync(tokenFile,'utf8')+'\n'+fs.readFileSync(path.join(path.dirname(tokenFile),'game-discovery.generated.css'),'utf8');
  const tokens = new Map([...css.matchAll(/(--ds-[\w-]+):\s*([^;]+);/g)].map(([,k,v])=>[k,v.trim()]));
  const colour = name => {
    const value=tokens.get(`--ds-${name}`);
    if (!value) throw Error(`Missing background colour token: ${name}`);
    const alias=/^var\(--ds-([\w-]+)\)$/.exec(value);
    return alias ? colour(alias[1]) : value;
  };
  const files = new Map();
  const put=(base,name,body)=>{if(base)files.set(path.join(base,name),body);};
  const hash=crypto.createHash('sha256').update(raw).update(fs.readFileSync(path.join(source,'artwork.mjs'),'utf8'));
  const overlay=cyberOverlay(colour);
  hash.update(overlay);
  put(webRoot,'public/assets/backgrounds/hub/cyber-overlay.svg',overlay);
  put(flutterRoot,'assets/backgrounds/hub/cyber-overlay.svg',overlay);
  for (const [theme,accent] of Object.entries(spec.themes)) {
    const materialNames=['ink','panel','edge','slate','pale','shadow','turf','turf-light','turf-deep','clay','clay-light','clay-deep','wood','wood-light','wood-deep','orange','orange-deep','red','red-deep','lime','court','court-light','court-deep','rubber','steel'];
    const palette={BASE:colour('color-background-primary'),SURFACE:colour('color-background-secondary'),EDGE:colour('color-border-default'),ACCENT:colour(`color-accent-${accent}`),...Object.fromEntries(materialNames.map(name=>[`M_${name.replaceAll('-','_').toUpperCase()}`,colour(`color-art-${name}`)]))};
    hash.update(JSON.stringify(palette));
    for (const [format,[w,h]] of Object.entries(spec.formats)) {
      const svg=artwork(theme,format,w,h,palette);
      put(webRoot,`public/assets/backgrounds/hub/${theme}-${format}.svg`,svg);
      put(flutterRoot,`assets/backgrounds/hub/${theme}-${format}.svg`,svg);
    }
  }
  const data={...spec,sourceHash:hash.digest('hex')};
  put(webRoot,'src/design-system/tokens/hub-backgrounds.generated.ts',`// Generated by scripts/sync-hub-backgrounds.mjs. Do not edit.\nexport const hubBackgrounds = ${JSON.stringify(data,null,2)} as const;\nexport type HubBackgroundTheme = keyof typeof hubBackgrounds.themes;\n`);
  const {css:overlayCss,dart}=overlayAdapters(data);
  put(webRoot,'src/design-system/components/layout/hub-backdrop/presentation.module.css',overlayCss);
  put(flutterRoot,'lib/widgets/cyber/hub_backgrounds.g.dart',dart);
  put(flutterRoot,'assets/backgrounds/hub/manifest.json',JSON.stringify(data,null,2)+'\n');
  return {files,data};
}

export function writeOrCheck(files, check) {
  const stale=[];
  for (const [name,body] of files) {
    if(fs.existsSync(name)&&fs.readFileSync(name,'utf8')===body)continue;
    if(check)stale.push(name);
    else{fs.mkdirSync(path.dirname(name),{recursive:true});fs.writeFileSync(name,body);}
  }
  if(stale.length)throw Error('Stale hub backgrounds; run npm run backgrounds:sync'+(stale.some(p=>p.includes('hub_backgrounds.g.dart'))?' -- --flutter-root <card_game>':'')+'\n'+stale.join('\n'));
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const index=process.argv.indexOf('--flutter-root');
  if(index>=0&&!process.argv[index+1])throw Error('--flutter-root needs the Flutter checkout path');
  const flutterRoot=index>=0?path.resolve(process.argv[index+1]):null;
  const result=generateHubBackgrounds(root,flutterRoot);
  writeOrCheck(result.files,process.argv.includes('--check'));
  console.log(`Hub backgrounds: ${Object.keys(result.data.themes).length} themes, ${result.files.size} local outputs ${process.argv.includes('--check')?'verified':'generated'}.`);
}
