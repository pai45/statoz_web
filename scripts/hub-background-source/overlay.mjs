export function overlayAdapters(spec) {
  const percent=value=>Math.round(value*10000)/100;
  const directions={
    vertical:{css:'to bottom',begin:'topCenter',end:'bottomCenter'},
    diagonal:{css:'to bottom right',begin:'topLeft',end:'bottomRight'},
    edge:{css:'to right',begin:'centerLeft',end:'centerRight'},
  };
  const gradients=Object.entries(spec.presentation.overlay);
  for(const [name,gradient]of gradients) {
    if(!directions[name]||gradient.stops.length!==gradient.alpha.length)throw Error(`Invalid hub overlay: ${name}`);
  }
  const cssGradients=gradients.map(([name,gradient])=>`linear-gradient(${directions[name].css}, ${gradient.alpha.map((alpha,i)=>`color-mix(in srgb, var(--ds-color-background-primary) ${percent(alpha)}%, transparent) ${percent(gradient.stops[i])}%`).join(', ')})`);
  const css=`/* Generated by scripts/sync-hub-backgrounds.mjs. */
.presentation { --hub-transition: ${spec.presentation.transitionMs}ms; }
.veil { background: url('/assets/backgrounds/hub/cyber-overlay.svg') 0 0 / 100% 100% no-repeat,\n  ${cssGradients.join(',\n  ')}; }
@media (min-width: ${spec.presentation.wideMinWidth}px) { .presentation > [data-hub-layer] { background-image: var(--hub-wide); } }
`;
  const dartGradients=gradients.map(([name,gradient])=>`  static LinearGradient get ${name}Overlay => LinearGradient(
    begin: Alignment.${directions[name].begin},
    end: Alignment.${directions[name].end},
    colors: [${gradient.alpha.map(alpha=>`Cyber.bg.withValues(alpha: ${alpha})`).join(', ')}],
    stops: const [${gradient.stops.join(', ')}],
  );`).join('\n');
  const dart=`// Generated by statoz_web/scripts/sync-hub-backgrounds.mjs. Do not edit.
import 'package:flutter/painting.dart';
import '../../config/theme.dart';

enum HubBackgroundTheme { ${Object.keys(spec.themes).join(', ')} }

abstract final class HubBackgroundSpec {
  static const sourceHash = '${spec.sourceHash}';
  static const transition = Duration(milliseconds: ${spec.presentation.transitionMs});
  static const wideMinWidth = ${spec.presentation.wideMinWidth}.0;
${dartGradients}
}
`;
  return {css,dart};
}
