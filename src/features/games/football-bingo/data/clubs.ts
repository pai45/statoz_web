/**
 * The clubs a career can name, and the crest codes the grid's axes wear.
 *
 * Ported from `_clubLabels` in `football_bingo_careers.dart` and the short
 * labels the puzzle blueprints carry on every `_axis`. Two clubs a career
 * mentions — Fiorentina and Udinese — are absent from the app's label table and
 * fall back to their own id, exactly as `_clubLabels[club] ?? club` does; the
 * chip uppercases either way, so the route still reads correctly.
 */

/** Display name for a club id. Falls back to the id, as the app does. */
export function clubLabel(clubId: string): string {
  return bingoClubLabels[clubId] ?? clubId;
}

/** The three-or-four letter code an axis badge prints. */
export function clubCode(clubId: string): string {
  return bingoClubCodes[clubId] ?? clubId.slice(0, 3).toUpperCase();
}

