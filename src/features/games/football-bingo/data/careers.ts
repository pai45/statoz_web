function parse(row: string): BingoCareer {
  const [id, name, shortName, clubs] = row.split("|");
  const clubIds = clubs.split(",");
  return {
    playerId: `bingo-${id}`,
    name,
    shortName,
    clubHistory: clubIds.map((clubId) => ({ clubId, label: clubLabel(clubId) })),
  };
}

export const bingoCareers: readonly BingoCareer[] = rows.map(parse);

const byId = new Map(bingoCareers.map((career) => [career.playerId, career]));

export function bingoCareerFor(playerId: string): BingoCareer | null {
  return byId.get(playerId) ?? null;
}

/** Whether a career includes senior appearances for a club. */
export function playedFor(career: BingoCareer, clubId: string): boolean {
  return career.clubHistory.some((spell) => spell.clubId === clubId);
}
